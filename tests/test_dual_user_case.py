import unittest
from pathlib import Path

from LnkParse3.offline_check import verify_lnk_with_msi


CASE_DIR = Path(__file__).resolve().parents[1] / "cases" / "dual_user_msi"
LNK_DIR = CASE_DIR / "lnk"
EXCERPT = CASE_DIR / "msi_registration_excerpt.json"


@unittest.skipUnless(EXCERPT.exists(), "dual-user dossier is generated by cases/dual_user_msi/build_case.py")
class DualUserDossierTests(unittest.TestCase):
    def test_bob_advertised_feature_file_has_no_installed_path(self):
        result = verify_lnk_with_msi(
            LNK_DIR / "bob-advertised-feature.lnk",
            EXCERPT,
            user="bob",
        )

        self.assertEqual(result["status"], "advertised_feature_only")
        self.assertFalse(result["installed"])
        self.assertEqual(result["installed_paths"], [])
        self.assertEqual(
            result["findings"][0]["registration_locators"],
            ["MSI-registration.txt:16"],
        )

    def test_conflicting_file_points_to_both_scopes_and_lines(self):
        result = verify_lnk_with_msi(
            LNK_DIR / "conflicting-encodings-user-vs-machine.lnk",
            EXCERPT,
            user="alice",
        )

        self.assertEqual(result["status"], "conflicting_darwin_claims")
        ansi = next(item for item in result["findings"] if item["encoding"] == "ansi")
        unicode_claim = next(item for item in result["findings"] if item["encoding"] == "unicode")
        self.assertEqual(ansi["registration_locators"], ["MSI-registration.txt:7"])
        self.assertEqual(unicode_claim["registration_locators"], ["MSI-registration.txt:12"])
        self.assertIn("offset=0x0000004c", ansi["block_locator"])


if __name__ == "__main__":
    unittest.main()
