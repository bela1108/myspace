"""
Impact comparison for STIX pattern time-qualifier changes.

This module answers a narrow review question: if a detection's time
qualifiers were changed, which observations would have matched the old
pattern but no longer match the new one?  It returns a shortest synthetic
event sequence witnessing the difference, or routes the patterns to manual
review when they fall outside the supported scope.

Supported scope
---------------

* Simple observation expressions (one bracket):
  ``[<opaque comparison expression>]``.  The comparison content is treated
  as an opaque condition label; it is not evaluated against observable
  values.
* ``FOLLOWEDBY`` chains of simple observation expressions.  Parentheses and
  nested ``FOLLOWEDBY`` nodes are flattened.
* ``START``/``STOP`` qualifiers anywhere on the expression tree.
* ``WITHIN N SECONDS`` qualifiers anywhere on the expression tree.
* Old and new patterns must use the same multiset of bracket conditions.
  This scopes the comparison to temporal changes (qualifiers and ordering)
  and prevents a changed condition from being mistaken for a time-window
  impact.

Semantics
---------

* ``START`` and ``STOP`` endpoints are inclusive.
* A degenerate window (``START == STOP``) contains exactly that instant.
* ``WITHIN N SECONDS`` is inclusive of the ``N``-second boundary.
* ``FOLLOWEDBY`` requires strictly increasing timestamps.  Two conditions
  observed at the exact same instant are not ordered for the purposes of
  ``FOLLOWEDBY``.

Anything else is outside the supported scope and is returned as
``ImpactStatus.MANUAL_REVIEW`` (or raises :class:`UnsupportedImpactPattern`
from :func:`matches_event_sequence`).  This includes observation-level
``AND``/``OR``, ``REPEATS``, condition-content changes and unparseable
patterns.  Witness synthesis is also bounded to at most four observations
and 200,000 candidate timestamp combinations; larger searches are routed to
manual review.
"""

import datetime
import itertools
import math
from collections import Counter
from dataclasses import dataclass
from enum import Enum
from typing import FrozenSet, Optional, Tuple

import pytz
from stix2patterns.exceptions import ParseException

from ... import pattern_visitor
from ...patterns import (
    AndObservationExpression, FollowedByObservationExpression,
    ObservationExpression, OrObservationExpression, ParentheticalExpression,
    QualifiedObservationExpression, RepeatQualifier, StartStopQualifier,
    WithinQualifier,
)
from ...utils import format_datetime, parse_into_datetime
from ...version import DEFAULT_VERSION

_UTC = pytz.utc
_ONE_MICROSECOND = datetime.timedelta(microseconds=1)
_EPOCH = datetime.datetime(1970, 1, 1, tzinfo=_UTC)

# The search is deliberately bounded.  Patterns outside these bounds are
# sent to manual review rather than risking an unbounded synthesis.
_MAX_SUPPORTED_OBSERVATIONS = 4
_MAX_CANDIDATE_TIMESTAMPS = 400
_MAX_WITNESS_COMBINATIONS = 200000


class ImpactStatus(str, Enum):
    """Outcome of a time-qualifier impact comparison."""

    UNCHANGED = "unchanged"
    """Both patterns accept exactly the synthetic sequences in scope."""

    LOST_MATCHES = "lost_matches"
    """Some observations matched the old pattern but not the new one."""

    GAINED_MATCHES = "gained_matches"
    """Some observations match the new pattern but not the old one."""

    LOST_AND_GAINED_MATCHES = "lost_and_gained_matches"
    """Both kinds of differences exist."""

    MANUAL_REVIEW = "manual_review"
    """The patterns are outside the supported scope or could not be parsed."""


class UnsupportedImpactPattern(ValueError):
    """Raised when a pattern is outside the impact-comparison scope."""


@dataclass(frozen=True)
class SyntheticEvent:
    """
    One synthetic observation used in a distinguishing event sequence.

    Args:
        timestamp: The observation time.  Naive datetimes are treated as UTC.
        conditions: The bracket condition labels satisfied by this
            observation.  For a witness generated by the impact comparison,
            each event normally satisfies one condition.
    """

    timestamp: datetime.datetime
    conditions: FrozenSet[str]

    def __post_init__(self):
        timestamp = self.timestamp
        if timestamp.tzinfo is None or timestamp.utcoffset() is None:
            timestamp = _UTC.localize(timestamp)
        object.__setattr__(self, "timestamp", timestamp)
        object.__setattr__(self, "conditions", frozenset(self.conditions))

    def __str__(self):
        conditions = " AND ".join(sorted(self.conditions))
        return "{} [{}]".format(
            format_datetime(self.timestamp), conditions,
        )


@dataclass(frozen=True)
class ImpactResult:
    """
    Result of :func:`compare_pattern_impact`.

    ``lost_match_witness`` is the shortest synthetic sequence which matches
    the old pattern and not the new one.  ``gained_match_witness`` is the
    reverse direction.  Both are ``None`` when no such sequence exists in
    the supported scope (or when manual review is required).
    """

    status: ImpactStatus
    lost_match_witness: Optional[Tuple[SyntheticEvent, ...]] = None
    gained_match_witness: Optional[Tuple[SyntheticEvent, ...]] = None
    old_satisfiable: Optional[bool] = None
    new_satisfiable: Optional[bool] = None
    manual_review_reason: Optional[str] = None

    @property
    def requires_manual_review(self):
        return self.status is ImpactStatus.MANUAL_REVIEW


@dataclass(frozen=True)
class _Skeleton:
    atoms: Tuple[str, ...]
    boundaries: Tuple[datetime.datetime, ...]
    within_seconds: Tuple[int, ...]


@dataclass(frozen=True)
class _Match:
    first_index: int
    last_index: int
    first_timestamp: datetime.datetime
    last_timestamp: datetime.datetime


def _strip_parentheses(ast):
    while isinstance(ast, ParentheticalExpression):
        ast = ast.expression
    return ast


def _flatten_followedby(ast):
    ast = _strip_parentheses(ast)
    if isinstance(ast, FollowedByObservationExpression):
        for child in ast.operands:
            yield from _flatten_followedby(child)
    else:
        yield ast


def _atom_key(operand):
    # Comparison expressions are opaque.  The canonical string is enough to
    # identify the same condition in the old and new patterns.
    return str(operand)


def _qualifier_time(value):
    if isinstance(value, str):
        return parse_into_datetime(value)
    return value


def _analyze(ast):
    """
    Validate the supported subset and extract its temporal skeleton.

    Raises:
        UnsupportedImpactPattern: if the AST contains unsupported syntax.
    """

    ast = _strip_parentheses(ast)

    if isinstance(ast, ObservationExpression):
        return _Skeleton((_atom_key(ast.operand),), (), ())

    elif isinstance(ast, FollowedByObservationExpression):
        atoms = []
        boundaries = []
        within_seconds = []
        for child in _flatten_followedby(ast):
            skeleton = _analyze(child)
            atoms.extend(skeleton.atoms)
            boundaries.extend(skeleton.boundaries)
            within_seconds.extend(skeleton.within_seconds)

        if len(atoms) > _MAX_SUPPORTED_OBSERVATIONS:
            raise UnsupportedImpactPattern(
                "FOLLOWEDBY chain has {} observations; the supported "
                "maximum is {}".format(
                    len(atoms), _MAX_SUPPORTED_OBSERVATIONS,
                ),
            )

        return _Skeleton(
            tuple(atoms), tuple(boundaries), tuple(within_seconds),
        )

    elif isinstance(ast, QualifiedObservationExpression):
        skeleton = _analyze(ast.observation_expression)
        qualifier = ast.qualifier

        if isinstance(qualifier, StartStopQualifier):
            start = _qualifier_time(qualifier.start_time.value)
            stop = _qualifier_time(qualifier.stop_time.value)
            return _Skeleton(
                skeleton.atoms,
                skeleton.boundaries + (start, stop),
                skeleton.within_seconds,
            )

        elif isinstance(qualifier, WithinQualifier):
            seconds = qualifier.number_of_seconds.value
            return _Skeleton(
                skeleton.atoms,
                skeleton.boundaries,
                skeleton.within_seconds + (seconds,),
            )

        elif isinstance(qualifier, RepeatQualifier):
            raise UnsupportedImpactPattern(
                "REPEATS qualifiers are outside the supported scope",
            )

        else:
            raise UnsupportedImpactPattern(
                "Unsupported qualifier: {}".format(type(qualifier).__name__),
            )

    elif isinstance(
        ast, (AndObservationExpression, OrObservationExpression),
    ):
        raise UnsupportedImpactPattern(
            "Observation-level AND/OR is outside the supported scope",
        )

    else:
        raise UnsupportedImpactPattern(
            "Unsupported observation expression: {}".format(
                type(ast).__name__,
            ),
        )


def _matches_node(ast, events):
    ast = _strip_parentheses(ast)

    if isinstance(ast, ObservationExpression):
        atom = _atom_key(ast.operand)
        return {
            _Match(index, index, event.timestamp, event.timestamp)
            for index, event in enumerate(events)
            if atom in event.conditions
        }

    elif isinstance(ast, FollowedByObservationExpression):
        matches = _matches_node(ast.operands[0], events)
        for child in ast.operands[1:]:
            child_matches = _matches_node(child, events)
            combined = set()
            for left in matches:
                for right in child_matches:
                    # FOLLOWEDBY is a strict ordering.
                    if left.last_timestamp < right.first_timestamp:
                        combined.add(
                            _Match(
                                left.first_index,
                                right.last_index,
                                left.first_timestamp,
                                right.last_timestamp,
                            ),
                        )
            matches = combined
            if not matches:
                break
        return matches

    elif isinstance(ast, QualifiedObservationExpression):
        matches = _matches_node(ast.observation_expression, events)
        qualifier = ast.qualifier

        if isinstance(qualifier, StartStopQualifier):
            start = _qualifier_time(qualifier.start_time.value)
            stop = _qualifier_time(qualifier.stop_time.value)
            # Both endpoints are inclusive.  A degenerate window therefore
            # still admits the exact instant.
            return {
                match for match in matches
                if start <= match.first_timestamp
                and match.last_timestamp <= stop
            }

        elif isinstance(qualifier, WithinQualifier):
            seconds = qualifier.number_of_seconds.value
            window = datetime.timedelta(seconds=seconds)
            return {
                match for match in matches
                if match.last_timestamp - match.first_timestamp <= window
            }

        elif isinstance(qualifier, RepeatQualifier):
            raise UnsupportedImpactPattern(
                "REPEATS qualifiers are outside the supported scope",
            )

        else:
            raise UnsupportedImpactPattern(
                "Unsupported qualifier: {}".format(type(qualifier).__name__),
            )

    elif isinstance(
        ast, (AndObservationExpression, OrObservationExpression),
    ):
        raise UnsupportedImpactPattern(
            "Observation-level AND/OR is outside the supported scope",
        )

    else:
        raise UnsupportedImpactPattern(
            "Unsupported observation expression: {}".format(
                type(ast).__name__,
            ),
        )


def _matches(ast, events):
    return bool(_matches_node(ast, events))


def _validate_event_sequence(events):
    last_timestamp = None
    for event in events:
        if not isinstance(event, SyntheticEvent):
            raise TypeError(
                "Event sequences must contain SyntheticEvent instances",
            )
        if last_timestamp is not None and event.timestamp < last_timestamp:
            raise ValueError(
                "Synthetic event sequences must be in non-decreasing "
                "timestamp order",
            )
        last_timestamp = event.timestamp


def matches_event_sequence(
    pattern, events, stix_version=DEFAULT_VERSION,
):
    """
    Evaluate a pattern against a synthetic event sequence using the same
    semantics as :func:`compare_pattern_impact`.

    Args:
        pattern: A STIX pattern string or an observation-expression AST.
        events: An iterable of :class:`SyntheticEvent` in non-decreasing
            timestamp order.
        stix_version: The STIX version to use for pattern parsing.

    Returns:
        True if the pattern matches the sequence.

    Raises:
        UnsupportedImpactPattern: if the pattern is outside the supported
            scope.
        ValueError: if events are not in timestamp order.
    """

    if isinstance(pattern, str):
        ast = pattern_visitor.create_pattern_object(
            pattern, version=stix_version,
        )
    else:
        ast = pattern

    _analyze(ast)
    event_sequence = tuple(events)
    _validate_event_sequence(event_sequence)
    return _matches(ast, event_sequence)


def _signed_offset_set(within_seconds, observation_count):
    """
    Build the interesting offsets used to place synthetic observations.

    Window bounds contribute absolute anchors.  WITHIN values contribute
    offsets, including combinations of up to three values, so a witness can
    sit just inside or outside a derived boundary.
    """

    offsets = {datetime.timedelta(0), _ONE_MICROSECOND, -_ONE_MICROSECOND}
    for count in range(1, observation_count + 1):
        offsets.add(count * _ONE_MICROSECOND)

    deltas = sorted(
        {datetime.timedelta(seconds=seconds) for seconds in within_seconds},
    )
    for delta in deltas:
        for sign in (1, -1):
            base = sign * delta
            offsets.update(
                (base, base + _ONE_MICROSECOND, base - _ONE_MICROSECOND),
            )

    for size in (2, 3):
        for delta_group in itertools.combinations(deltas, size):
            for signs in itertools.product((1, -1), repeat=size):
                base = sum(
                    (sign * delta for sign, delta in zip(signs, delta_group)),
                    datetime.timedelta(0),
                )
                offsets.update(
                    (base, base + _ONE_MICROSECOND, base - _ONE_MICROSECOND),
                )

    return offsets


def _candidate_timestamps(skeletons, observation_count):
    boundaries = sorted(
        {
            boundary
            for skeleton in skeletons
            for boundary in skeleton.boundaries
        },
    )
    within_seconds = sorted(
        {
            seconds
            for skeleton in skeletons
            for seconds in skeleton.within_seconds
        },
    )

    offsets = _signed_offset_set(within_seconds, observation_count)
    anchors = boundaries or [_EPOCH]
    if not boundaries:
        # With no absolute bounds, there is no need to look before the epoch;
        # keeping offsets non-negative yields a cleaner canonical witness.
        offsets = {
            offset for offset in offsets
            if offset >= datetime.timedelta(0)
        }

    candidates = {
        anchor + offset
        for anchor in anchors
        for offset in offsets
    }

    # An interior point just between adjacent window bounds is useful when
    # neither endpoint survives in the other pattern.
    for left, right in zip(boundaries, boundaries[1:]):
        candidates.add(left + ((right - left) // 2))

    candidates = sorted(candidates)
    if len(candidates) > _MAX_CANDIDATE_TIMESTAMPS:
        raise UnsupportedImpactPattern(
            "Timeline has {} candidate instants; the supported maximum is "
            "{}".format(len(candidates), _MAX_CANDIDATE_TIMESTAMPS),
        )

    return candidates


def _search_witness(
    match_ast, reject_ast, atoms, skeletons, observation_count,
):
    """
    Search for the shortest sequence matching ``match_ast`` and not
    ``reject_ast``.

    Since only FOLLOWEDBY is supported, a matching sequence needs one event
    per bracket occurrence, in the flattened atom order.  Searching
    combinations of candidate timestamps is therefore exhaustive for this
    scope.
    """

    candidates = _candidate_timestamps(skeletons, observation_count)
    event_count = len(atoms)

    combination_count = math.comb(len(candidates), event_count)
    if combination_count > _MAX_WITNESS_COMBINATIONS:
        raise UnsupportedImpactPattern(
            "Witness search needs {} timestamp combinations; the supported "
            "maximum is {}".format(
                combination_count, _MAX_WITNESS_COMBINATIONS,
            ),
        )

    best = None
    for timestamps in itertools.combinations(candidates, event_count):
        events = tuple(
            SyntheticEvent(timestamp, frozenset((atom,)))
            for atom, timestamp in zip(atoms, timestamps)
        )

        if not _matches(match_ast, events):
            continue
        if reject_ast is not None and _matches(reject_ast, events):
            continue

        span = timestamps[-1] - timestamps[0]
        candidate_key = (event_count, span, timestamps)
        if best is None or candidate_key < best[0]:
            best = (candidate_key, events)

    return None if best is None else best[1]


def _manual_review(reason):
    return ImpactResult(
        status=ImpactStatus.MANUAL_REVIEW,
        manual_review_reason=reason,
    )


def compare_pattern_impact(
    old_pattern, new_pattern, stix_version=DEFAULT_VERSION,
):
    """
    Compare the impact of a time-qualifier change between two STIX patterns.

    The comparison is scoped to temporal changes: ordering, ``START``/
    ``STOP`` windows and ``WITHIN`` qualifiers.  The non-temporal bracket
    conditions must be unchanged (as a multiset); otherwise manual review is
    requested.  See the module docstring for the full supported scope and
    boundary semantics.

    Args:
        old_pattern: The previous pattern string.
        new_pattern: The updated pattern string.
        stix_version: The STIX version to use for parsing.

    Returns:
        :class:`ImpactResult`.  ``lost_match_witness`` is the shortest
        synthetic sequence matching the old pattern but not the new one.
        ``gained_match_witness`` is the reverse direction.  If either pattern
        is outside the supported scope, the result's status is
        ``MANUAL_REVIEW`` and ``manual_review_reason`` explains why.
    """

    try:
        old_ast = pattern_visitor.create_pattern_object(
            old_pattern, version=stix_version,
        )
    except (ParseException, TypeError, ValueError) as exc:
        return _manual_review(
            "Old pattern parsing failed: {}".format(exc),
        )

    try:
        new_ast = pattern_visitor.create_pattern_object(
            new_pattern, version=stix_version,
        )
    except (ParseException, TypeError, ValueError) as exc:
        return _manual_review(
            "New pattern parsing failed: {}".format(exc),
        )

    try:
        old_skeleton = _analyze(old_ast)
    except UnsupportedImpactPattern as exc:
        return _manual_review("Old pattern: {}".format(exc))

    try:
        new_skeleton = _analyze(new_ast)
    except UnsupportedImpactPattern as exc:
        return _manual_review("New pattern: {}".format(exc))

    old_conditions = Counter(old_skeleton.atoms)
    new_conditions = Counter(new_skeleton.atoms)
    if old_conditions != new_conditions:
        return _manual_review(
            "Non-temporal bracket conditions changed; the impact comparison "
            "only covers time qualifiers and FOLLOWEDBY ordering. "
            "Old conditions: {}; new conditions: {}".format(
                sorted(old_conditions.elements()),
                sorted(new_conditions.elements()),
            ),
        )

    observation_count = max(
        len(old_skeleton.atoms), len(new_skeleton.atoms),
    )
    skeletons = (old_skeleton, new_skeleton)

    try:
        old_satisfiable = bool(
            _search_witness(
                old_ast, None, old_skeleton.atoms, skeletons,
                observation_count,
            )
        )
        new_satisfiable = bool(
            _search_witness(
                new_ast, None, new_skeleton.atoms, skeletons,
                observation_count,
            )
        )

        lost_witness = _search_witness(
            old_ast, new_ast, old_skeleton.atoms, skeletons,
            observation_count,
        )
        gained_witness = _search_witness(
            new_ast, old_ast, new_skeleton.atoms, skeletons,
            observation_count,
        )
    except UnsupportedImpactPattern as exc:
        return _manual_review(str(exc))

    if lost_witness and gained_witness:
        status = ImpactStatus.LOST_AND_GAINED_MATCHES
    elif lost_witness:
        status = ImpactStatus.LOST_MATCHES
    elif gained_witness:
        status = ImpactStatus.GAINED_MATCHES
    else:
        status = ImpactStatus.UNCHANGED

    return ImpactResult(
        status=status,
        lost_match_witness=lost_witness,
        gained_match_witness=gained_witness,
        old_satisfiable=old_satisfiable,
        new_satisfiable=new_satisfiable,
    )
